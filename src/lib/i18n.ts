export type TranslationKey = keyof typeof ko;

// Module-level cache: ko is always present; other languages loaded on demand
export const translationCache: Record<string, Translations> = { ko };

export const translations: Record<string, Translations> = translationCache;

export async function loadLang(lang: Lang): Promise<Translations> {
  if (lang === 'ko') return ko;
  if (translationCache[lang]) return translationCache[lang];
  const loaders: Record<string, () => Promise<{ default: Translations }>> = {
    en: () => import('@/lib/translations/en'),
    ja: () => import('@/lib/translations/ja'),
    zh: () => import('@/lib/translations/zh'),
    es: () => import('@/lib/translations/es'),
    fr: () => import('@/lib/translations/fr'),
    it: () => import('@/lib/translations/it'),
    de: () => import('@/lib/translations/de'),
    pt: () => import('@/lib/translations/pt'),
    ru: () => import('@/lib/translations/ru'),
    no: () => import('@/lib/translations/no'),
    nl: () => import('@/lib/translations/nl'),
  };
  const mod = await loaders[lang]?.();
  if (mod) translationCache[lang] = mod.default;
  return translationCache[lang] ?? ko;
}
